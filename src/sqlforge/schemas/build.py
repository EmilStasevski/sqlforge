"""Build the three source databases under data/db/.

  tpch    -> data/db/tpch.duckdb     (train)    generated by DuckDB's tpch extension
  smard   -> data/db/smard.duckdb    (train)    raw SMARD 15-min series; dbt builds marts on top (dbt/smard)
  weather -> data/db/weather.duckdb  (test_ood) Open-Meteo historical weather for 6 NRW cities

Usage: uv run python -m sqlforge.schemas.build [tpch|smard|weather|all]
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import time
from pathlib import Path

import duckdb
import pyarrow as pa
import requests

DB_DIR = Path("data/db")
RAW_DIR = Path("data/raw")
TPCH_SF = 0.1

# Ruhrwatt's bronze layer (reuse, don't redo). Override with SQLFORGE_SMARD_BRONZE.
RUHRWATT_BRONZE = Path(
    os.environ.get(
        "SQLFORGE_SMARD_BRONZE",
        Path.home() / "industrial-big-data-stack/ruhrwatt/data/bronze/smard",
    )
)

# City coordinates are inputs (approximate city centres), not results.
CITIES = [
    (1, "Dortmund", 51.5136, 7.4653),
    (2, "Köln", 50.9375, 6.9603),
    (3, "Düsseldorf", 51.2277, 6.7735),
    (4, "Essen", 51.4556, 7.0116),
    (5, "Münster", 51.9607, 7.6261),
    (6, "Bonn", 50.7374, 7.0982),
]
WEATHER_START, WEATHER_END = "2023-01-01", "2024-12-31"
DAILY_VARS = [
    "temperature_2m_max",
    "temperature_2m_min",
    "temperature_2m_mean",
    "precipitation_sum",
    "rain_sum",
    "snowfall_sum",
    "sunshine_duration",
    "wind_speed_10m_max",
    "wind_gusts_10m_max",
]
HOURLY_VARS = [
    "temperature_2m",
    "relative_humidity_2m",
    "precipitation",
    "cloud_cover",
    "wind_speed_10m",
    "pressure_msl",
]


def _fresh(path: Path) -> duckdb.DuckDBPyConnection:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.unlink(missing_ok=True)
    return duckdb.connect(str(path))


def build_tpch() -> Path:
    path = DB_DIR / "tpch.duckdb"
    con = _fresh(path)
    con.execute("INSTALL tpch; LOAD tpch;")
    con.execute(f"CALL dbgen(sf={TPCH_SF});")
    con.close()
    return path


def build_smard() -> Path:
    raw = RAW_DIR / "smard"
    if not raw.exists():
        if not RUHRWATT_BRONZE.exists():
            raise SystemExit(
                f"SMARD bronze not found at {RUHRWATT_BRONZE}. Set SQLFORGE_SMARD_BRONZE "
                "(standalone SMARD downloader: TODO Day 2)."
            )
        shutil.copytree(RUHRWATT_BRONZE, raw)
    path = DB_DIR / "smard.duckdb"
    con = _fresh(path)
    con.execute(
        f"""CREATE TABLE smard_raw AS
        SELECT ts_utc, dataset, region, value, is_native_15min
        FROM read_parquet('{raw}/**/*.parquet', hive_partitioning = true)
        ORDER BY dataset, region, ts_utc"""
    )
    con.close()
    return path


def _fetch_city(lat: float, lon: float, cache: Path) -> dict:
    if cache.exists():
        return json.loads(cache.read_text())
    params = {
        "latitude": lat,
        "longitude": lon,
        "start_date": WEATHER_START,
        "end_date": WEATHER_END,
        "daily": ",".join(DAILY_VARS),
        "hourly": ",".join(HOURLY_VARS),
        "timezone": "Europe/Berlin",
    }
    for attempt in range(5):
        r = requests.get("https://archive-api.open-meteo.com/v1/archive", params=params, timeout=60)
        if r.status_code == 200:
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_text(r.text)
            return r.json()
        time.sleep(2**attempt)
    r.raise_for_status()
    raise RuntimeError("unreachable")


def build_weather() -> Path:
    path = DB_DIR / "weather.duckdb"
    con = _fresh(path)
    con.execute(
        """CREATE TABLE city (city_id INTEGER PRIMARY KEY, name VARCHAR, latitude DOUBLE,
           longitude DOUBLE, elevation_m DOUBLE)"""
    )
    daily_cols = ", ".join(f"{v} DOUBLE" for v in DAILY_VARS)
    hourly_cols = ", ".join(f"{v} DOUBLE" for v in HOURLY_VARS)
    con.execute(f"CREATE TABLE weather_daily (city_id INTEGER REFERENCES city, date DATE, {daily_cols})")
    con.execute(f"CREATE TABLE weather_hourly (city_id INTEGER REFERENCES city, ts TIMESTAMP, {hourly_cols})")
    for cid, name, lat, lon in CITIES:
        d = _fetch_city(lat, lon, RAW_DIR / "openmeteo" / f"city_{cid}.json")
        con.execute("INSERT INTO city VALUES (?, ?, ?, ?, ?)", [cid, name, lat, lon, d.get("elevation")])
        # Arrow bulk insert (executemany is row-by-row and ~100x slower).
        daily = pa.table(
            {
                "city_id": [cid] * len(d["daily"]["time"]),
                "date": d["daily"]["time"],
                **{v: pa.array(d["daily"][v], pa.float64()) for v in DAILY_VARS},
            }
        )
        con.register("daily", daily)
        con.execute(
            "INSERT INTO weather_daily SELECT city_id, CAST(date AS DATE), * EXCLUDE (city_id, date) "
            "FROM daily"
        )
        hourly = pa.table(
            {
                "city_id": [cid] * len(d["hourly"]["time"]),
                "ts": d["hourly"]["time"],
                **{v: pa.array(d["hourly"][v], pa.float64()) for v in HOURLY_VARS},
            }
        )
        con.register("hourly", hourly)
        con.execute(
            "INSERT INTO weather_hourly SELECT city_id, CAST(ts AS TIMESTAMP), * EXCLUDE (city_id, ts) "
            "FROM hourly"
        )
    con.close()
    return path


BUILDERS = {"tpch": build_tpch, "smard": build_smard, "weather": build_weather}


def summary(path: Path) -> dict[str, int]:
    con = duckdb.connect(str(path), read_only=True)
    tables = [
        r[0] for r in con.execute("SELECT table_name FROM information_schema.tables ORDER BY 1").fetchall()
    ]
    out = {t: con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0] for t in tables}
    con.close()
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("which", nargs="?", default="all", choices=[*BUILDERS, "all"])
    args = ap.parse_args()
    for name in BUILDERS if args.which == "all" else [args.which]:
        t0 = time.time()
        p = BUILDERS[name]()
        print(f"{name}: {p} ({time.time() - t0:.1f}s) {summary(p)}")


if __name__ == "__main__":
    main()
